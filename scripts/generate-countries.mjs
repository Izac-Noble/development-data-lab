#!/usr/bin/env node
/**
 * Regenerates src/data/countries.generated.ts, the bundled country catalog.
 *
 *   npm run generate:countries
 *
 * Sources:
 * - World Bank country API (keyless): which economies have indicator data, plus region,
 *   income group and capital. Aggregates such as "World" or "Sub-Saharan Africa" are skipped.
 * - REST Countries v5 (needs REST_COUNTRIES_API_KEY, read from the environment or from
 *   dashboard-backend/.env): display and official names, flag, currency, the country's centre
 *   coordinates (for map pins) and its ISO numeric code (to match map outlines).
 *
 * The key is only used by this script at build time; it never ends up in the generated file.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = resolve(root, 'src/data/countries.generated.ts');

function readApiKey() {
  if (process.env.REST_COUNTRIES_API_KEY) {
    return process.env.REST_COUNTRIES_API_KEY.trim();
  }
  try {
    const env = readFileSync(resolve(root, 'dashboard-backend/.env'), 'utf8');
    return /^REST_COUNTRIES_API_KEY=(.*)$/m.exec(env)?.[1].trim() ?? '';
  } catch {
    return '';
  }
}

async function getJson(url, headers = {}) {
  const response = await fetch(url, { headers });
  if (!response.ok) {
    throw new Error(`${new URL(url).host} returned HTTP ${response.status}`);
  }
  return response.json();
}

async function worldBankEconomies() {
  const [, rows] = await getJson('https://api.worldbank.org/v2/country?format=json&per_page=400');
  return rows
    .filter((row) => row.region?.id && row.region.id !== 'NA') // 'NA' marks aggregates
    .map((row) => ({
      code: row.id,
      name: row.name.trim(),
      region: row.region.value.trim(),
      incomeGroup: row.incomeLevel?.value?.trim() || 'Not classified',
      capital: row.capitalCity?.trim() || '',
      latitude: Number(row.latitude) || 0,
      longitude: Number(row.longitude) || 0,
    }));
}

async function restCountriesRecords(apiKey) {
  const fields = 'codes.alpha_3,codes.ccn3,names.common,names.official,flag.emoji,currencies,coordinates,capitals';
  const records = [];
  for (let offset = 0; ; offset += 100) {
    const payload = await getJson(
      `https://api.restcountries.com/countries/v5?limit=100&offset=${offset}&response_fields=${fields}`,
      { Authorization: `Bearer ${apiKey}` },
    );
    if (payload.data?._demo) {
      throw new Error('REST Countries returned demo data; set a real REST_COUNTRIES_API_KEY');
    }
    records.push(...(payload.data?.objects ?? []));
    if (!payload.data?.meta?.more) {
      return new Map(records.map((record) => [record.codes?.alpha_3, record]));
    }
  }
}

const round = (value) => Math.round(value * 1000) / 1000;

async function main() {
  const apiKey = readApiKey();
  if (!apiKey) {
    throw new Error('Set REST_COUNTRIES_API_KEY (environment or dashboard-backend/.env)');
  }

  const [economies, restByCode] = await Promise.all([worldBankEconomies(), restCountriesRecords(apiKey)]);

  const countries = economies
    .map((economy) => {
      const rest = restByCode.get(economy.code);
      if (!rest) {
        return null; // Not a sovereign country in REST Countries (e.g. Channel Islands, Kosovo).
      }
      const primaryCapital = rest.capitals?.find((capital) => capital.attributes?.primary) ?? rest.capitals?.[0];
      return {
        code: economy.code,
        name: rest.names?.common || economy.name,
        officialName: rest.names?.official || economy.name,
        flag: rest.flag?.emoji || '',
        region: economy.region,
        incomeGroup: economy.incomeGroup,
        capital: economy.capital || primaryCapital?.name || 'Unknown',
        currency: (rest.currencies ?? []).map((currency) => currency.name).filter(Boolean).join(', ') || 'Unknown',
        latitude: round(rest.coordinates?.lat ?? economy.latitude),
        longitude: round(rest.coordinates?.lng ?? economy.longitude),
        ...(rest.codes?.ccn3 ? { isoNumeric: String(rest.codes.ccn3).padStart(3, '0') } : {}),
      };
    })
    .filter(Boolean)
    .sort((a, b) => a.name.localeCompare(b.name));

  if (countries.length < 100) {
    throw new Error(`Only ${countries.length} countries matched; refusing to shrink the catalog`);
  }

  const file = `// Generated by scripts/generate-countries.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Sources: World Bank country API (region, income group, capital) and REST Countries v5.
import type { CountryProfile } from '../types';

export const COUNTRY_CATALOG: CountryProfile[] = ${JSON.stringify(countries, null, 2)};
`;
  writeFileSync(outputPath, file);
  console.log(`Wrote ${countries.length} countries to ${outputPath}`);
  const skipped = economies.filter((economy) => !restByCode.has(economy.code)).map((economy) => economy.code);
  if (skipped.length) {
    console.log(`Skipped (no REST Countries record): ${skipped.join(', ')}`);
  }
}

main().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
